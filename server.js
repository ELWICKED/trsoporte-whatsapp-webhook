// =====================================================
// BUSCAR / CREAR CLIENTE
// =====================================================

async function obtenerCliente(
    telefono,
    nombre
) {

    const {
        data: existente,
        error: errorBusqueda
    } =
        await supabase
            .from("clientes")
            .select("*")
            .eq(
                "telefono",
                telefono
            )
            .maybeSingle();

    if (errorBusqueda) {

        throw errorBusqueda;
    }

    if (existente) {

        /*
         * Si WhatsApp ahora devuelve nombre,
         * actualizamos el nombre si estaba vacío.
         */

        if (
            nombre &&
            !existente.nombre
        ) {

            await supabase
                .from("clientes")
                .update({
                    nombre:
                        nombre
                })
                .eq(
                    "id",
                    existente.id
                );

            existente.nombre =
                nombre;
        }

        return existente;
    }

    const {
        data: nuevo,
        error
    } =
        await supabase
            .from("clientes")
            .insert({

                telefono:
                    telefono,

                nombre:
                    nombre ||
                    telefono,

                activo:
                    true,

                baja_comunicaciones:
                    false
            })
            .select()
            .single();

    if (error) {

        throw error;
    }

    return nuevo;
}

