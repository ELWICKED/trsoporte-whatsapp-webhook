// PROCESAR WEBHOOK
// =====================================================

async function manejarWebhook(
    req,
    res
) {

    try {

        const data =
            await leerBody(
                req
            );

        console.log("");
        console.log(
            "========================================="
        );
        console.log(
            "WEBHOOK DE WHATSAPP RECIBIDO"
        );
        console.log(
            "========================================="
        );

        console.log(
            JSON.stringify(
                data,
                null,
                2
            )
        );

        const entries =
            data.entry || [];

        for (
            const entry
            of entries
        ) {

            const changes =
                entry.changes || [];

            for (
                const change
                of changes
            ) {

                const value =
                    change.value;

                if (!value) {
                    continue;
                }

                const messages =
                    value.messages || [];

                /*
                 * IMPORTANTE:
                 *
                 * Los eventos de status (delivered,
                 * read, sent) NO contienen messages.
                 *
                 * Simplemente los ignoramos.
                 */

                if (
                    messages.length === 0
                ) {

                    continue;
                }

                for (
                    const message
                    of messages
                ) {

                    try {

                        const esMarketing =
                            await marketingRegistrarEventoWebhook(
                                message,
                                value
                            );

                        if (esMarketing) {
                            console.log(
                                "Mensaje de Marketing procesado sin crear ticket:",
                                message.id
                            );
                            continue;
                        }

                        await procesarMensajeEntrante(
                            message,
                            value
                        );

                        console.log(
                            "Mensaje procesado correctamente:",
                            message.id
                        );

                    } catch (errorMensaje) {

                        console.error(
                            "ERROR PROCESANDO MENSAJE:",
                            errorMensaje
                        );
                    }
                }
            }
        }

        responderJSON(
            res,
            200,
            {
                success:
                    true
            }
        );

    } catch (error) {

        console.error(
            "ERROR PROCESANDO WEBHOOK:",
            error
        );

        /*
         * Respondemos 200 para evitar que Meta
         * reintente indefinidamente el webhook.
         */

        responderJSON(
            res,
            200,
            {
                success:
                    false,

                error:
                    error.message
            }
        );
    }
}

