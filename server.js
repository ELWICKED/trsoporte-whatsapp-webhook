// =====================================================
// GUARDAR MEDIA EN SUPABASE STORAGE
// =====================================================

async function guardarMediaStorage(
    media,
    telefono,
    messageId
) {

    const extension =
        obtenerExtension(
            media.mimeType
        );

    const nombreArchivo =
        `${Date.now()}_${messageId}${extension}`;

    const path =
        `${telefono}/${nombreArchivo}`;

    const {
        error
    } =
        await supabase
            .storage
            .from(
                WHATSAPP_MEDIA_BUCKET
            )
            .upload(
                path,
                media.buffer,
                {
                    contentType:
                        media.mimeType,

                    upsert:
                        false
                }
            );

    if (error) {

        throw error;
    }

    /*
     * Bucket privado:
     * generamos URL firmada.
     */

    let mediaUrl =
        null;

    const {
        data: signedData,
        error: signedError
    } =
        await supabase
            .storage
            .from(
                WHATSAPP_MEDIA_BUCKET
            )
            .createSignedUrl(
                path,
                60 * 60 * 24 * 30
            );

    if (
        !signedError &&
        signedData
    ) {

        mediaUrl =
            signedData.signedUrl;
    }

    return {

        bucket:
            WHATSAPP_MEDIA_BUCKET,

        path:
            path,

        url:
            mediaUrl,

        mime_type:
            media.mimeType,

        media_id:
            media.mediaId,

        nombre_archivo:
            nombreArchivo,

        tamano:
            media.buffer.length
    };
}

// =====================================================
// OBTENER DATOS MULTIMEDIA DEL MENSAJE
// =====================================================

function obtenerDatosMedia(
    message
) {

    const tipo =
        message.type;

    if (
        tipo === "image" &&
        message.image
    ) {

        return {

            mediaId:
                message.image.id,

            mimeType:
                message.image.mime_type ||
                "image/jpeg",

            caption:
                message.image.caption ||
                null
        };
    }

    if (
        tipo === "video" &&
        message.video
    ) {

        return {

            mediaId:
                message.video.id,

            mimeType:
                message.video.mime_type ||
                "video/mp4",

            caption:
                message.video.caption ||
                null
        };
    }

    if (
        tipo === "audio" &&
        message.audio
    ) {

        return {

            mediaId:
                message.audio.id,

            mimeType:
                message.audio.mime_type ||
                "audio/ogg",

            caption:
                null
        };
    }

    if (
        tipo === "document" &&
        message.document
    ) {

        return {

            mediaId:
                message.document.id,

            mimeType:
                message.document.mime_type ||
                "application/octet-stream",

            caption:
                message.document.caption ||
                null,

            filename:
                message.document.filename ||
                null
        };
    }

    if (
        tipo === "sticker" &&
        message.sticker
    ) {

        return {

            mediaId:
                message.sticker.id,

            mimeType:
                message.sticker.mime_type ||
                "image/webp",

            caption:
                null
        };
    }

    return null;
}

// =====================================================
// PROCESAR MULTIMEDIA
// =====================================================

async function procesarMultimedia(
    message,
    telefono
) {

    const datos =
        obtenerDatosMedia(
            message
        );

    if (!datos) {

        return null;
    }

    console.log(
        "Procesando multimedia:",
        message.type
    );

    const media =
        await descargarMediaWhatsApp(
            datos.mediaId
        );

    const archivo =
        await guardarMediaStorage(
            media,
            telefono,
            message.id
        );

    return {

        tipo:
            message.type,

        media_id:
            datos.mediaId,

        mime_type:
            media.mimeType,

        media_url:
            archivo.url,

        media_path:
            archivo.path,

        bucket:
            archivo.bucket,

        nombre_archivo:
            datos.filename ||
            archivo.nombre_archivo,

        tamano:
            archivo.tamano,

        caption:
            datos.caption ||
            null
    };
}

