function responderJSON(
    res,
    statusCode,
    data
) {

    if (res.headersSent) {
        return;
    }

    res.writeHead(
        statusCode,
        {
            "Content-Type":
                "application/json; charset=utf-8"
        }
    );

    res.end(
        JSON.stringify(data)
    );
}

// =====================================================
// LEER BODY
// =====================================================

function leerBody(req) {

    return new Promise(
        (
            resolve,
            reject
        ) => {

            let body = "";

            req.on(
                "data",
                chunk => {

                    body +=
                        chunk.toString();
                }
            );

            req.on(
                "end",
                () => {

                    if (!body) {

                        resolve({});

                        return;
                    }

                    try {

                        resolve(
                            JSON.parse(
                                body
                            )
                        );

                    } catch {

                        reject(
                            new Error(
                                "JSON inválido."
                            )
                        );
                    }
                }
            );

            req.on(
                "error",
                reject
            );
        }
    );
}

// =====================================================
// OBTENER ID DE TICKET
// =====================================================

function obtenerIdTicket(
    pathname
) {

    const partes =
        pathname
            .split("/")
            .filter(Boolean);

    if (
        partes.length !== 2 ||
        partes[0] !== "tickets"
    ) {

        return null;
    }

    const id =
        Number(
            partes[1]
        );

    if (
        !Number.isInteger(id) ||
        id <= 0
    ) {

        return null;
    }

    return id;
}

