async function actualizarBloqueoCliente(
    clienteId,
    bloqueado,
    agenteId = null
) {

    if (!Number.isInteger(clienteId) || clienteId <= 0) {

        throw new Error(
            "ID de cliente inválido."
        );
    }

    const {
        data: cliente,
        error
    } =
        await supabase
            .from("clientes")
            .update({
                bloqueado:
                    Boolean(bloqueado)
            })
            .eq(
                "id",
                clienteId
            )
            .select("*")
            .single();

    if (error) {

        throw error;
    }

    // Si existe un ticket abierto para el cliente, dejamos
    // constancia del bloqueo/desbloqueo en su historial.
    const {
        data: conversacion,
        error: errorConversacion
    } =
        await supabase
            .from("conversaciones")
            .select("id")
            .eq(
                "cliente_id",
                clienteId
            )
            .eq(
                "estado",
                "abierta"
            )
            .order(
                "ultima_interaccion",
                {
                    ascending: false
                }
            )
            .limit(1)
            .maybeSingle();

    if (errorConversacion) {

        throw errorConversacion;
    }

    if (conversacion) {

        await registrarHistorial(
            conversacion.id,
            agenteId,
            bloqueado
                ? "cliente_bloqueado"
                : "cliente_desbloqueado",
            bloqueado
                ? "El cliente fue bloqueado por un agente. Los nuevos mensajes serán ignorados."
                : "El cliente fue desbloqueado por un agente. Los nuevos mensajes volverán a procesarse normalmente."
        );
    }

    return cliente;
}


