// =====================================================
// DESCARGAR MEDIA DESDE WHATSAPP
// =====================================================

async function descargarMediaWhatsApp(
    mediaId
) {

    if (!mediaId) {

        throw new Error(
            "No se recibió media_id."
        );
    }

    const infoUrl =
        `https://graph.facebook.com/v26.0/${mediaId}`;

    const infoResponse =
        await fetch(
            infoUrl,
            {
                method: "GET",

                headers: {
                    "Authorization":
                        `Bearer ${ACCESS_TOKEN}`
                }
            }
        );

    const info =
        await infoResponse.json();

    if (!infoResponse.ok) {

        throw new Error(
            info?.error?.message ||
            "No se pudo obtener información del archivo multimedia."
        );
    }

    const mediaUrl =
        info.url;

    const mimeType =
        info.mime_type ||
        "application/octet-stream";

    if (!mediaUrl) {

        throw new Error(
            "Meta no devolvió URL multimedia."
        );
    }

    const mediaResponse =
        await fetch(
            mediaUrl,
            {
                method: "GET",

                headers: {
                    "Authorization":
                        `Bearer ${ACCESS_TOKEN}`
                }
            }
        );

    if (!mediaResponse.ok) {

        const errorText =
            await mediaResponse.text();

        throw new Error(
            `No se pudo descargar multimedia: ${errorText}`
        );
    }

    const arrayBuffer =
        await mediaResponse.arrayBuffer();

    return {

        buffer:
            Buffer.from(
                arrayBuffer
            ),

        mimeType:
            mimeType,

        mediaId:
            mediaId,

        originalUrl:
            mediaUrl
    };
}

