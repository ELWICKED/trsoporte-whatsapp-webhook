// =====================================================
// PROCESAR MENSAJE ENTRANTE
// =====================================================

async function procesarMensajeEntrante(
    message,
    value
) {

    const telefono =
        message.from;

    if (!telefono) {

        console.log(
            "Mensaje ignorado: sin teléfono."
        );

        return;
    }

    const nombre =
        value
            ?.contacts?.[0]
            ?.profile?.name ||
        telefono;

    const whatsappMessageId =
        message.id ||
        null;

    const tipo =
        message.type ||
        "unknown";

    console.log(
        "Cliente:",
        nombre
    );

    console.log(
        "Teléfono:",
        telefono
    );

    console.log(
        "Tipo de mensaje:",
        tipo
    );

    // =================================================
    // EVITAR DUPLICADOS
    // =================================================

    if (whatsappMessageId) {

        const {
            data: existente,
            error
        } =
            await supabase
                .from("mensajes")
                .select("id")
                .eq(
                    "whatsapp_message_id",
                    whatsappMessageId
                )
                .maybeSingle();

        if (error) {

            throw error;
        }

        if (existente) {

            console.log(
                "Mensaje duplicado ignorado:",
                whatsappMessageId
            );

            return;
        }
    }

    // =================================================
    // CLIENTE
    // =================================================

    const cliente =
        await obtenerCliente(
            telefono,
            nombre
        );

    // =================================================
    // CLIENTE BLOQUEADO
    // =================================================

    // El bloqueo es manual y lo realiza un agente desde
    // el sistema. Un cliente bloqueado no genera tickets,
    // no procesa multimedia y no recibe respuestas automáticas.
    if (cliente.bloqueado === true) {

        console.log(
            "Mensaje ignorado: cliente bloqueado.",
            telefono
        );

        return;
    }

    // =================================================
    // CALIFICACIÓN
    // =================================================

    const contenidoTexto =
        message.type === "text" &&
        message.text
            ? String(
                message.text.body
            ).trim()
            : "";

    const esCalificacion =
        message.type === "text" &&
        /^[1-5]$/.test(
            contenidoTexto
        );

    if (esCalificacion) {

        const {
            data: ultimaConversacion,
            error
        } =
            await supabase
                .from("conversaciones")
                .select("*")
                .eq(
                    "cliente_id",
                    cliente.id
                )
                .order(
                    "creado_en",
                    {
                        ascending:
                            false
                    }
                )
                .limit(1)
                .maybeSingle();

        if (error) {

            throw error;
        }

        if (
            ultimaConversacion &&
            ultimaConversacion.estado ===
                "cerrada"
        ) {

            await supabase
                .from("mensajes")
                .insert({

                    cliente_id:
                        cliente.id,

                    conversacion_id:
                        ultimaConversacion.id,

                    whatsapp_message_id:
                        whatsappMessageId,

                    direccion:
                        "entrante",

                    tipo:
                        "text",

                    contenido:
                        contenidoTexto,

                    estado:
                        "recibido"
                });

            const {
                error:
                    errorCalificacion
            } =
                await supabase
                    .from("conversaciones")
                    .update({

                        calificacion:
                            Number(
                                contenidoTexto
                            ),

                        calificado_en:
                            new Date()
                                .toISOString()
                    })
                    .eq(
                        "id",
                        ultimaConversacion.id
                    );

            if (errorCalificacion) {

                throw errorCalificacion;
            }

            await registrarHistorial(
                ultimaConversacion.id,
                ultimaConversacion.agente_id,
                "ticket_calificado",
                `El cliente calificó la atención con ${contenidoTexto}/5.`
            );

            const gracias =
                `⭐ Gracias por calificar la atención del ticket #${ultimaConversacion.numero_ticket}.\n\nTu valoración fue registrada correctamente.\n\n¡Gracias por confiar en TR Soporte!`;

            const resultado =
                await enviarWhatsApp(
                    telefono,
                    gracias
                );

            await guardarMensajeSaliente(
                ultimaConversacion,
                gracias,
                ultimaConversacion.agente_id,
                resultado
                    ?.messages?.[0]?.id ||
                null
            );

            console.log(
                `Calificación ${contenidoTexto}/5 registrada.`
            );

            return;
        }
    }

    // =================================================
    // CONVERSACIÓN ABIERTA
    // =================================================

    let conversacion =
        await obtenerConversacionAbierta(
            cliente.id
        );

    let ticketCreado =
        false;

    if (!conversacion) {

        conversacion =
            await crearConversacion(
                cliente.id
            );

        ticketCreado =
            true;

        console.log(
            "Nueva conversación creada:",
            conversacion.id
        );

        console.log(
            "Número de ticket:",
            conversacion.numero_ticket
        );
    }

    // =================================================
    // MULTIMEDIA
    // =================================================

    let multimedia =
        null;

    if (
        [
            "image",
            "video",
            "audio",
            "document",
            "sticker"
        ].includes(
            tipo
        )
    ) {

        try {

            multimedia =
                await procesarMultimedia(
                    message,
                    telefono
                );

            console.log(
                "Multimedia guardada:",
                multimedia
            );

        } catch (error) {

            console.error(
                "ERROR PROCESANDO MULTIMEDIA:",
                error
            );

            /*
             * No perdemos el mensaje.
             * Guardamos una referencia textual
             * aunque falle Storage.
             */

            multimedia = {

                tipo:
                    tipo,

                error:
                    error.message
            };
        }
    }

    // =================================================
    // CONTENIDO
    // =================================================

    const contenido =
        obtenerContenidoMensaje(
            message,
            multimedia
        );

    // =================================================
    // NÚMERO DE MENSAJE ENTRANTE
    // =================================================

    const mensajesEntrantesAntes =
        await contarMensajesEntrantes(
            conversacion.id
        );

    const numeroMensaje =
        mensajesEntrantesAntes + 1;

    console.log(
        "Mensaje entrante número:",
        numeroMensaje
    );

    // =================================================
    // GUARDAR MENSAJE
    // =================================================

    const {
        error: errorMensaje
    } =
        await supabase
            .from("mensajes")
            .insert({

                cliente_id:
                    cliente.id,

                conversacion_id:
                    conversacion.id,

                whatsapp_message_id:
                    whatsappMessageId,

                direccion:
                    "entrante",

                tipo:
                    tipo,

                contenido:
                    contenido,

                estado:
                    "recibido"
            });

    if (errorMensaje) {

        throw errorMensaje;
    }

    console.log(
        "Mensaje guardado correctamente."
    );

    // =================================================
    // ACTUALIZAR CLIENTE
    // =================================================

    await supabase
        .from("clientes")
        .update({

            ultima_interaccion:
                new Date()
                    .toISOString()
        })
        .eq(
            "id",
            cliente.id
        );

    // =================================================
    // ACTUALIZAR CONVERSACIÓN
    // =================================================

    await supabase
        .from("conversaciones")
        .update({

            ultima_interaccion:
                new Date()
                    .toISOString()
        })
        .eq(
            "id",
            conversacion.id
        );

    // =================================================
    // HISTORIAL
    // =================================================

    if (ticketCreado) {

        await registrarHistorial(
            conversacion.id,
            null,
            "ticket_creado",
            "Ticket creado automáticamente desde WhatsApp."
        );

    } else {

        await registrarHistorial(
            conversacion.id,
            conversacion.agente_id,
            "mensaje_recibido",
            multimedia
                ? `El cliente envió un mensaje multimedia (${tipo}).`
                : "El cliente envió un nuevo mensaje por WhatsApp."
        );
    }

    // =================================================
    // RESPUESTAS AUTOMÁTICAS
    // =================================================

    let respuestaAutomatica =
        null;

    // -----------------------------------------------
    // PRIMER MENSAJE
    // -----------------------------------------------

    if (
        numeroMensaje === 1
    ) {

        respuestaAutomatica =
            "Hola 👋 Gracias por comunicarte con TR Soporte. Recibimos tu mensaje correctamente.\n\nMientras tanto, contanos brevemente cuál es el problema que estás teniendo para que podamos ayudarte mejor. 🛠️";
    }

    // -----------------------------------------------
    // SEGUNDO MENSAJE
    // -----------------------------------------------

    else if (
        numeroMensaje === 2
    ) {

        respuestaAutomatica =
            `📋 Tu número de caso es #${conversacion.numero_ticket}.\n\nGracias por la información. Un agente de soporte revisará tu solicitud y se comunicará con vos.\n\nPor favor, aguardá el contacto del agente.`;
    }

    // -----------------------------------------------
    // TERCERO EN ADELANTE
    // -----------------------------------------------

    else {

        console.log(
            "No se envía respuesta automática."
        );
    }

    // =================================================
    // ENVIAR RESPUESTA AUTOMÁTICA
    // =================================================

    if (
        respuestaAutomatica
    ) {

        console.log(
            "Enviando respuesta automática..."
        );

        const resultado =
            await enviarWhatsApp(
                telefono,
                respuestaAutomatica
            );

        const whatsappRespuestaId =
            resultado
                ?.messages?.[0]?.id ||
            null;

        await guardarMensajeSaliente(
            conversacion,
            respuestaAutomatica,
            null,
            whatsappRespuestaId
        );

        console.log(
            "Respuesta automática enviada correctamente."
        );
    }
}

