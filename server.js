// =====================================================
// LISTAR TICKETS
// =====================================================

async function obtenerTickets(
    buscar = ""
) {

    const {
        data: conversaciones,
        error
    } =
        await supabase
            .from("conversaciones")
            .select(`
                *,
cliente:clientes(
    id,
    nombre,
    telefono,
    empresa,
    bloqueado
),
                agente:agentes(
                    id,
                    nombre,
                    rol,
                    area,
                    activo
                )
            `)
            .order(
                "ultima_interaccion",
                {
                    ascending:
                        false
                }
            );

    if (error) {

        throw error;
    }

    let tickets =
        conversaciones || [];

    const texto =
        String(
            buscar || ""
        )
            .trim()
            .toLowerCase();

    if (texto) {

        tickets =
            tickets.filter(
                ticket => {

                    const numero =
                        String(
                            ticket.numero_ticket ||
                            ""
                        ).toLowerCase();

                    const nombre =
                        String(
                            ticket.cliente?.nombre ||
                            ""
                        ).toLowerCase();

                    const telefono =
                        String(
                            ticket.cliente?.telefono ||
                            ""
                        ).toLowerCase();

                    const empresa =
                        String(
                            ticket.cliente?.empresa ||
                            ""
                        ).toLowerCase();

                    const estado =
                        String(
                            ticket.estado ||
                            ""
                        ).toLowerCase();

                    const prioridad =
                        String(
                            ticket.prioridad ||
                            ""
                        ).toLowerCase();

                    const categoria =
                        String(
                            ticket.categoria ||
                            ""
                        ).toLowerCase();

                    const agente =
                        String(
                            ticket.agente?.nombre ||
                            ""
                        ).toLowerCase();

                    return (
                        numero.includes(texto) ||
                        nombre.includes(texto) ||
                        telefono.includes(texto) ||
                        empresa.includes(texto) ||
                        estado.includes(texto) ||
                        prioridad.includes(texto) ||
                        categoria.includes(texto) ||
                        agente.includes(texto)
                    );
                }
            );
    }

    return tickets;
}

