// =====================================================
// WHATSAPP - ENVIAR TEXTO
// =====================================================

async function enviarWhatsApp(
    telefono,
    mensaje
) {

    if (!ACCESS_TOKEN) {

        throw new Error(
            "META_ACCESS_TOKEN no configurado."
        );
    }

    if (!PHONE_NUMBER_ID) {

        throw new Error(
            "META_PHONE_NUMBER_ID no configurado."
        );
    }

    const whatsappUrl =
        `https://graph.facebook.com/v26.0/${PHONE_NUMBER_ID}/messages`;

    console.log(
        "Enviando WhatsApp a:",
        telefono
    );

    const response =
        await fetch(
            whatsappUrl,
            {
                method: "POST",

                headers: {
                    "Authorization":
                        `Bearer ${ACCESS_TOKEN}`,

                    "Content-Type":
                        "application/json"
                },

                body:
                    JSON.stringify({

                        messaging_product:
                            "whatsapp",

                        recipient_type:
                            "individual",

                        to:
                            telefono,

                        type:
                            "text",

                        text: {

                            preview_url:
                                false,

                            body:
                                mensaje
                        }
                    })
            }
        );

    const result =
        await response.json();

    console.log(
        "Respuesta de Meta:",
        JSON.stringify(
            result
        )
    );

    if (!response.ok) {

        throw new Error(
            result?.error?.message ||
            "Meta rechazó el mensaje."
        );
    }

    return result;
}

