async function enviarWhatsAppMarketing(
    telefono
) {
    if (!MARKETING_ENABLED) {
        throw new Error(
            "Marketing está deshabilitado. Configure MARKETING_ENABLED=true."
        );
    }

    if (!MARKETING_ACCESS_TOKEN) {
        throw new Error(
            "MARKETING_ACCESS_TOKEN no configurado."
        );
    }

    if (!MARKETING_PHONE_NUMBER_ID) {
        throw new Error(
            "MARKETING_PHONE_NUMBER_ID no configurado."
        );
    }

    const telefonoNormalizado =
        marketingNormalizarTelefono(
            telefono
        );

    if (
        !telefonoNormalizado ||
        telefonoNormalizado.length < 8
    ) {
        throw new Error(
            "Número de teléfono de Marketing inválido."
        );
    }

    const whatsappUrl =
        `https://graph.facebook.com/${MARKETING_API_VERSION}/${MARKETING_PHONE_NUMBER_ID}/messages`;

    const plantilla = {
        messaging_product:
            "whatsapp",

        recipient_type:
            "individual",

        to:
            telefonoNormalizado,

        type:
            "template",

        template: {
            name:
                MARKETING_TEMPLATE_NAME,

            language: {
                code:
                    MARKETING_TEMPLATE_LANGUAGE
            }
        }
    };

    console.log(
        "[MARKETING] Enviando plantilla:",
        MARKETING_TEMPLATE_NAME,
        "a:",
        telefonoNormalizado
    );

    const response =
        await fetch(
            whatsappUrl,
            {
                method:
                    "POST",

                headers: {
                    "Authorization":
                        `Bearer ${MARKETING_ACCESS_TOKEN}`,

                    "Content-Type":
                        "application/json"
                },

                body:
                    JSON.stringify(
                        plantilla
                    )
            }
        );

    const resultado =
        await response.json();

    if (!response.ok) {
        console.error(
            "[MARKETING] Error de Meta:",
            resultado
        );

        throw new Error(
            resultado?.error?.message ||
            "Meta rechazó la plantilla de Marketing."
        );
    }

    return resultado;
}

async function marketingEnviarContacto(
    campanaId,
    marketingContactoId
) {
    const idCampana =
        Number(
            campanaId
        );

    if (
        !Number.isInteger(idCampana) ||
        idCampana <= 0
    ) {
        throw new Error(
            "campana_id inválido."
        );
    }

    const contacto =
        await marketingObtenerContactoPorId(
            marketingContactoId
        );

    const envio =
        await marketingCrearEnvioPendiente(
            idCampana,
            contacto.id
        );

    if (
        envio.estado === "enviado"
    ) {
        return {
            envio:
                envio,

            contacto:
                contacto,

            ya_enviado:
                true
        };
    }

    try {
        const resultado =
            await enviarWhatsAppMarketing(
                contacto.telefono
            );

        const messageId =
            resultado
                ?.messages?.[0]?.id ||
            null;

        await marketingMarcarEnvio(
            envio.id,
            {
                whatsapp_message_id:
                    messageId,

                estado:
                    "enviado",

                enviado_en:
                    new Date()
                        .toISOString(),

                error:
                    null
            }
        );

        return {
            envio_id:
                envio.id,

            campana_id:
                idCampana,

            marketing_contacto_id:
                contacto.id,

            telefono:
                contacto.telefono,

            whatsapp_message_id:
                messageId,

            estado:
                "enviado",

            ya_enviado:
                false,

            whatsapp:
                resultado
        };
    }
    catch (errorEnvio) {

        await marketingMarcarEnvio(
            envio.id,
            {
                estado:
                    "error",

                error:
                    errorEnvio.message
            }
        );

        throw errorEnvio;
    }
}

async function marketingRegistrarEventoWebhook(
    message,
    value
) {
    const from =
        marketingNormalizarTelefono(
            message?.from
        );

    if (!from) {
        return false;
    }

    const contacto =
        await marketingBuscarContactoPorTelefono(
            from
        );

    if (!contacto) {
        return false;
    }

    const messageId =
        message?.id || null;

    const tipo =
        message?.type || "unknown";

    console.log(
        `[MARKETING] Respuesta/evento recibido de ${from}. Tipo: ${tipo}`
    );

    if (messageId) {
        const { data: envio } =
            await supabase
                .from("envios_marketing")
                .select("*")
                .eq(
                    "marketing_contacto_id",
                    contacto.id
                )
                .order(
                    "id",
                    { ascending: false }
                )
                .limit(1)
                .maybeSingle();

        if (envio) {
            await marketingMarcarEnvio(
                envio.id,
                {
                    respondido_en:
                        envio.respondido_en ||
                        new Date()
                            .toISOString()
                }
            );
        }
    }

    // Guardamos la marca de respuesta en el contacto/campaña,
    // pero NO creamos tickets de Soporte desde este flujo.
    return true;
}


