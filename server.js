async function guardarMensajeSaliente(
    conversacion,
    mensaje,
    agenteId = null,
    whatsappMessageId = null
) {

    const {
        error: errorMensaje
    } =
        await supabase
            .from("mensajes")
            .insert({

                cliente_id:
                    conversacion.cliente_id,

                conversacion_id:
                    conversacion.id,

                whatsapp_message_id:
                    whatsappMessageId,

                direccion:
                    "saliente",

                tipo:
                    "text",

                contenido:
                    mensaje,

                estado:
                    "enviado"
            });

    if (errorMensaje) {

        throw errorMensaje;
    }

    const {
        error:
            errorActualizacion
    } =
        await supabase
            .from("conversaciones")
            .update({

                ultima_interaccion:
                    new Date()
                        .toISOString()
            })
            .eq(
                "id",
                conversacion.id
            );

    if (errorActualizacion) {

        throw errorActualizacion;
    }

    await registrarHistorial(
        conversacion.id,
        agenteId,
        "mensaje_enviado",
        agenteId
            ? "El agente envió un mensaje al cliente por WhatsApp."
            : "Mensaje automático enviado al cliente por WhatsApp."
    );
}

